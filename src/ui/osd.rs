impl Canvas<'_> {
    pub(super) fn osd_width(text: &str) -> i32 {
        (text.chars().count() as i32 * 6 - 1).max(0)
    }
    pub(super) fn osd(&mut self, x: i32, y: i32, text: &str, color: [u8; 3]) {
        self.osd_glyphs(x, y, text, color, (5, 7));
    }
    pub(super) fn osd_right(&mut self, right: i32, y: i32, text: &str, color: [u8; 3]) {
        self.osd(right - Self::osd_width(text), y, text, color);
    }
    pub(super) fn osd_value(&mut self, x: i32, y: i32, text: &str, color: [u8; 3]) {
        self.osd_glyphs(x, y, text, color, (7, 10));
    }
    fn osd_glyphs(&mut self, x: i32, y: i32, text: &str, color: [u8; 3], size: (i32, i32)) {
        let (width, height) = size;
        for outline in [true, false] {
            for (i, ch) in text.chars().enumerate() {
                let rows = glyph(ch);
                for yy in 0..height {
                    for xx in 0..width {
                        if rows[(yy * 7 / height) as usize] & (1 << (4 - xx * 5 / width)) == 0 {
                            continue;
                        }
                        let (px, py) = (x + i as i32 * (width + 1) + xx, y + yy);
                        if outline {
                            for (dx, dy) in [(-1, 0), (1, 0), (0, -1), (0, 1)] {
                                self.pixel(px + dx, py + dy, [3, 8, 13]);
                            }
                        } else {
                            self.pixel(px, py, color);
                        }
                    }
                }
            }
        }
    }
}
