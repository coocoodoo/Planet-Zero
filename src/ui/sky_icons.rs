#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn icons_are_eleven_by_eleven_and_distinct() {
        let all = [
            Icon::Scan,
            Icon::Mine,
            Icon::Land,
            Icon::Dock,
            Icon::Map,
            Icon::Bag,
            Icon::Jet,
            Icon::Board,
            Icon::Prev,
            Icon::Next,
            Icon::Warp,
            Icon::System,
            Icon::Close,
            Icon::Use,
            Icon::Craft,
            Icon::Make,
            Icon::Grid,
            Icon::Sell,
            Icon::Buy,
            Icon::Upgrade,
            Icon::Confirm,
            Icon::Undock,
            Icon::Fire,
            Icon::Swap,
            Icon::Open,
            Icon::Read,
            Icon::Signal,
            Icon::Arms,
            Icon::Equip,
            Icon::Scrap,
        ];
        let mut seen = std::collections::HashSet::new();
        for icon in all {
            let rows = bitmap(icon);
            for row in rows {
                assert_eq!(row.len(), 11, "{icon:?}");
            }
            assert!(seen.insert(rows), "{icon:?} duplicates another icon");
        }
    }
}
